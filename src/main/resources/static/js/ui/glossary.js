/** Word with a tooltip. */
export function term(key, text) {
  return h('span', {class: 'term', dataset: {term: key}, tabindex: 0}, text || key);
}

let tip = null;
let tipFor = null;   // узел, к которому подсказка привязана: если его убрали, подсказку надо снять

export function installTooltips() {
  const show = (el) => {
    const def = TERMS[el.dataset.term] || el.dataset.tip;
    if (!def) return;
    hide();
    tip = h('div', {class: 'tip', role: 'tooltip'}, def);
    tipFor = el;
    document.body.appendChild(tip);
    const r = el.getBoundingClientRect();
    const tw = tip.offsetWidth;
    tip.style.left = Math.max(8, Math.min(window.innerWidth - tw - 8, r.left)) + 'px';
    tip.style.top = (r.bottom + 6 + tip.offsetHeight > window.innerHeight ? r.top - tip.offsetHeight - 6 : r.bottom + 6) + 'px';
  };
  const hide = () => {
    if (tip) tip.remove();
    tip = null;
    tipFor = null;
  };
  // панель могла перерисоваться и унести элемент вместе с собой — мышь при этом не двигалась
  setInterval(() => { if (tip && tipFor && !tipFor.isConnected) hide(); }, 300);
  document.addEventListener('mouseover', (e) => {
    const t = e.target.closest('[data-term],[data-tip]');
    if (t) show(t); else hide();
  });
  document.addEventListener('focusin', (e) => {
    const t = e.target.closest('[data-term],[data-tip]');
    if (t) show(t);
  });
  document.addEventListener('focusout', hide);
  document.addEventListener('scroll', hide, true);
}

